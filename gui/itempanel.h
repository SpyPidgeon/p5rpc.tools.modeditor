struct ItemTables
{
    std::array<AccessoryItem, AccessoryItem::ACCESSORY_SIZE> accessories;
    std::array<Armor, Armor::ARMOR_SIZE> armors;
    std::array<Consumable, Consumable::CONSUMABLE_SIZE> consumables;
    std::array<KeyItem, KeyItem::KEY_ITEM_SIZE> keyItems;
    std::array<Treasure, Treasure::TREASURE_SIZE> treasures;
    std::array<Melee, Melee::MELEE_SIZE> melees;
    std::array<Outfit, Outfit::OUTFIT_SIZE> outfits;
    std::array<SkillCard, SkillCard::SKILL_CARD_SIZE> skillCards;
    std::array<RangedWeapon, RangedWeapon::RANGED_SIZE> rangedWeapons;
};
VISITABLE_STRUCT(ItemTables, accessories, armors, consumables, keyItems, treasures, melees, outfits, skillCards, rangedWeapons);

struct ItemPointers
{
    std::array<AccessoryItem, AccessoryItem::ACCESSORY_SIZE>* accessories;
    std::array<Armor, Armor::ARMOR_SIZE>* armors;
    std::array<Consumable, Consumable::CONSUMABLE_SIZE>* consumables;
    std::array<KeyItem, KeyItem::KEY_ITEM_SIZE>* keyItems;
    std::array<Treasure, Treasure::TREASURE_SIZE>* treasures;
    std::array<Melee, Melee::MELEE_SIZE>* melees;
    std::array<Outfit, Outfit::OUTFIT_SIZE>* outfits;
    std::array<SkillCard, SkillCard::SKILL_CARD_SIZE>* skillCards;
    std::array<RangedWeapon, RangedWeapon::RANGED_SIZE>* rangedWeapons;
};
VISITABLE_STRUCT(ItemPointers, accessories, armors, consumables, keyItems, treasures, melees, outfits, skillCards, rangedWeapons);

struct ItemNames
{
    std::array<std::string, AccessoryItem::ACCESSORY_SIZE> accessory;
    std::array<std::string, Armor::ARMOR_SIZE> armor;
    std::array<std::string, Consumable::CONSUMABLE_SIZE> consumable;
    std::array<std::string, KeyItem::KEY_ITEM_SIZE> keyItem;
    std::array<std::string, Treasure::TREASURE_SIZE> treasure;
    std::array<std::string, Melee::MELEE_SIZE> melee;
    std::array<std::string, Outfit::OUTFIT_SIZE> outfit;
    std::array<std::string, SkillCard::SKILL_CARD_SIZE> skillCard;
    std::array<std::string, RangedWeapon::RANGED_SIZE> rangedWeapon;
};
VISITABLE_STRUCT(ItemNames, accessory, armor, consumable, keyItem, treasure, melee, outfit, skillCard,
    rangedWeapon);

